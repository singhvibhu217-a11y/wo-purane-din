/* =========================================================
   PLAY SELECTED SONG
========================================================= */

function playSong(index) {

    if (
        index < 0 ||
        index >= songs.length
    ) {

        return;

    }


    currentSongIndex =
        index;


    const song =
        songs[index];


    document
        .getElementById("playerSong")
        .textContent =
        song.name;


    document
        .getElementById("playerArtist")
        .textContent =
        song.artist;


    /*
    EncodeURI helps with spaces in filenames.
    Example:
    Aa Chal Ke Tujhe.mp3
    */

    audio.src =
        encodeURI(song.file);


    audio
        .play()
        .then(() => {

            setPlayerState(true);

            markCurrentSong();

        })
        .catch(error => {

            console.error(
                "Song play nahi hua:",
                song.file,
                error
            );


            setPlayerState(false);

        });

}


/* =========================================================
   PLAY / PAUSE
========================================================= */

function togglePlay() {

    if (
        currentSongIndex < 0
    ) {

        /*
        First currently visible song
        */

        const firstCard =
            document.querySelector(
                ".song"
            );


        if (firstCard) {

            playSong(
                Number(
                    firstCard.dataset.index
                )
            );

        }

        else {

            playSong(0);

        }


        return;

    }


    if (audio.paused) {

        audio
            .play()
            .then(() => {

                setPlayerState(true);

            })
            .catch(console.error);

    }

    else {

        audio.pause();

        setPlayerState(false);

    }

}


