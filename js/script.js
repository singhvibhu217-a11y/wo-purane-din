/* =========================================================
   NORMALIZE ERA
========================================================= */

/*
Examples:

"80"   -> "80"
"80s"  -> "80"
"80's" -> "80"

"90"   -> "90"
"90s"  -> "90"
"90's" -> "90"
*/

function normalizeEra(value) {

    return String(value)
        .replace(/[^0-9]/g, "");

}


/* =========================================================
   RENDER SONGS
========================================================= */

function renderSongs(filter = "all") {

    const grid =
        document.getElementById("songGrid");

    if (!grid) {

        console.error(
            "songGrid element nahi mila."
        );

        return;
    }


    grid.innerHTML = "";


    const normalizedFilter =
        filter === "all"
            ? "all"
            : normalizeEra(filter);


    let visibleSongs = 0;


    songs.forEach((song, index) => {

        const songEra =
            normalizeEra(song.era);


        /*
        Skip if it doesn't match selected era
        */

        if (
            normalizedFilter !== "all" &&
            songEra !== normalizedFilter
        ) {

            return;

        }


        visibleSongs++;


        const card =
            document.createElement("article");


        card.className =
            "song";


        card.dataset.index =
            index;


        /*
        Keep playing card highlighted
        */

        if (
            index === currentSongIndex
        ) {

            card.classList.add(
                "active"
            );

        }


        card.innerHTML = `

            <div class="cover">

                <div class="mini-vinyl"></div>

                <div class="song-year">
                    ${song.year}
                </div>

            </div>


            <div class="song-info">

                <div class="song-name">
                    ${song.name}
                </div>

                <div class="song-artist">
                    ${song.artist}
                </div>

                <div class="song-era">
                    ${songEra}'s golden melody
                </div>

            </div>


            <div class="song-actions">

                <span
                class="heart"
                title="Add to favourites">
                    ♡
                </span>

                <span
                class="play-circle">
                    ▶
                </span>

            </div>
        `;


        /* ================================
           FAVOURITE
        ================================= */

        const heart =
            card.querySelector(
                ".heart"
            );


        heart.addEventListener(
            "click",
            event => {

                event.stopPropagation();


                heart.classList.toggle(
                    "active"
                );


                heart.textContent =
                    heart.classList.contains(
                        "active"
                    )
                        ? "♥"
                        : "♡";

            }
        );


        /* ================================
           PLAY SONG
        ================================= */

        card.addEventListener(
            "click",
            () => {

                playSong(index);

            }
        );


        grid.appendChild(card);

    });


    /* =================================================
       NOTHING FOUND
    ================================================= */

    if (visibleSongs === 0) {

        grid.innerHTML = `

            <div class="empty-playlist">

                <div class="empty-note">
                    ♫
                </div>

                <h3>
                    Is zamaane ke gaane nahi mile
                </h3>

                <p>
                    Song ki era value check karein.
                </p>

                <button
                onclick="showAllSongs()">
                    Show All Songs
                </button>

            </div>
        `;

    }


    markCurrentSong();

}


