let chimeContext = null;


function playChime() {

    const AudioContextType =
        window.AudioContext ||
        window.webkitAudioContext;


    if (!AudioContextType) {

        return;

    }


    if (!chimeContext) {

        chimeContext =
            new AudioContextType();

    }


    if (
        chimeContext.state ===
        "suspended"
    ) {

        chimeContext.resume();

    }


    const now =
        chimeContext.currentTime;


    createTone(
        523.25,
        now,
        .18,
        .025
    );


    createTone(
        659.25,
        now + .06,
        .22,
        .018
    );

}


function createTone(
    frequency,
    start,
    duration,
    volume
) {

    const oscillator =
        chimeContext
            .createOscillator();


    const gain =
        chimeContext
            .createGain();


    oscillator.type =
        "sine";


    oscillator.frequency
        .setValueAtTime(
            frequency,
            start
        );


    gain.gain
        .setValueAtTime(
            .0001,
            start
        );


    gain.gain
        .exponentialRampToValueAtTime(
            volume,
            start + .015
        );


    gain.gain
        .exponentialRampToValueAtTime(
            .0001,
            start + duration
        );


    oscillator.connect(
        gain
    );


    gain.connect(
        chimeContext.destination
    );


    oscillator.start(
        start
    );


    oscillator.stop(
        start +
        duration +
        .03
    );

}


