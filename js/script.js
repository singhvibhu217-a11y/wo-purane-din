/* =========================================================
   SEEK
========================================================= */

function seek(event) {

    if (
        !Number.isFinite(
            audio.duration
        )
    ) {

        return;

    }


    const rect =
        event
            .currentTarget
            .getBoundingClientRect();


    let ratio =
        (
            event.clientX -
            rect.left
        )
        /
        rect.width;


    ratio =
        Math.max(
            0,
            Math.min(1, ratio)
        );


    audio.currentTime =
        ratio *
        audio.duration;

}


/* =========================================================
   TIME
========================================================= */

function formatTime(seconds) {

    if (
        !Number.isFinite(seconds)
    ) {

        return "0:00";

    }


    const minutes =
        Math.floor(
            seconds / 60
        );


    const secs =
        Math.floor(
            seconds % 60
        )
        .toString()
        .padStart(
            2,
            "0"
        );


    return (
        minutes +
        ":" +
        secs
    );

}


