function markCurrentSong() {

    document
        .querySelectorAll(".song")
        .forEach(card => {

            const index =
                Number(
                    card.dataset.index
                );


            card.classList.toggle(
                "active",
                index === currentSongIndex
            );

        });

}


/* =========================================================
   FILTERED NEXT/PREVIOUS

   80s list ke andar ho to next button
   80s ka next song hi play karega.

   90s list mein ho to 90s ka next song.
========================================================= */

function getCurrentVisibleIndexes() {

    if (
        currentFilter === "all"
    ) {

        return songs.map(
            (_, index) => index
        );

    }


    return songs
        .map(
            (song, index) => ({
                song,
                index
            })
        )
        .filter(
            item =>
                normalizeEra(
                    item.song.era
                )
                ===
                currentFilter
        )
        .map(
            item => item.index
        );

}


/* NEXT */

function nextSong() {

    const indexes =
        getCurrentVisibleIndexes();


    if (
        indexes.length === 0
    ) {

        return;

    }


    const position =
        indexes.indexOf(
            currentSongIndex
        );


    const nextPosition =
        position < 0
            ? 0
            : (
                position + 1
            ) % indexes.length;


    playSong(
        indexes[nextPosition]
    );

}


/* PREVIOUS */

function previousSong() {

    const indexes =
        getCurrentVisibleIndexes();


    if (
        indexes.length === 0
    ) {

        return;

    }


    const position =
        indexes.indexOf(
            currentSongIndex
        );


    const previousPosition =
        position < 0
            ? indexes.length - 1
            : (
                position - 1 +
                indexes.length
            ) % indexes.length;


    playSong(
        indexes[
            previousPosition
        ]
    );

}


